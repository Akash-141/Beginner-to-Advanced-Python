# For loop example
for i in range(1, 6):
    print(i)

# Loop through string
word = "Code"
for char in word:
    print(char)

# While loop example
count = 5
while count > 0:
    print(count)
    count -= 1

# Break example
for i in range(10):
    if i == 7:
        break
    print(i)

# Continue example
for i in range(6):
    if i % 2 == 0:
        continue
    print(i)
