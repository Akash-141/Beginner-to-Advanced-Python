
print("Day 16: Python Lists Examples")

# Creating a list
numbers = [10, 20, 30, 40]
print(numbers)

# List with mixed data types
data = [10, "Python", 3.14, True]
print(data)

# Accessing list elements
fruits = ["apple", "banana", "mango"]
print(fruits[0])
print(fruits[1])

# Negative indexing
print(fruits[-1])

# Modifying list values
numbers = [1, 2, 3]
numbers[1] = 10
print(numbers)

# Getting length of list
items = ["pen", "book", "eraser"]
print(len(items))

# Nested lists
matrix = [
    [1, 2, 3],
    [4, 5, 6]
]

print(matrix[0])
print(matrix[1][2])

# Iterating through a list
numbers = [10, 20, 30]
for number in numbers:
    print(number)

# Grouped data example
students = ["Ali", "Sara", "John"]
for student in students:
    print(student)

print("End of Day 16 examples")

