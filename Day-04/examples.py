print("Day 4: Variables and Data Types Examples")

# Example 1: Creating variables
name = "Akash"
age = 21
height = 5.8

print(name, age, height)

# Example 2: Valid variable names
user_name = "Akash"
_age = 21
totalScore = 95

print(user_name, _age, totalScore)

# Example 3: Integer
age = 25
print(type(age))

# Example 4: Float
price = 19.99
print(type(price))

# Example 5: String
message = "Hello, Python"
print(type(message))

# Example 6: Boolean
is_logged_in = True
print(type(is_logged_in))

# Example 7: Type conversion
age = 21
age_str = str(age)

print(type(age))
print(type(age_str))

# Example 8: Multiple assignment
x, y, z = 10, 20, 30
print(x, y, z)

# Example 9: Dynamic typing example
value = 10
value = "ten"
print(value)

print("End of Day 4 examples")
